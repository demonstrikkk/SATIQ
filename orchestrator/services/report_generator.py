"""Report generation — PDF/DOCX from session task_outputs.
Sections: query, methodology, results with charts, confidence, audit trace, thumbnails.
Uses reportlab for PDF if available, else fallback to simple HTML bytes.
"""
from __future__ import annotations
import json
import io
from pathlib import Path
from typing import List, Dict, Any, Literal

def _html_for_pdf(session_id: str, task_outputs: List[Dict[str, Any]]) -> str:
    rows = ""
    for i, out in enumerate(task_outputs):
        rows += f"""
        <div style="border:1px solid #222; padding:12px; margin:12px 0;">
          <h3>{i+1}. {out.get('task','unknown')} — {out.get('query','')[:80]}</h3>
          <p><b>Answer:</b> {out.get('answer_text','')[:400]}</p>
          <p>Confidence: {out.get('confidence') or out.get('per_modality_confidence',{}).get('fused','')} | Encoder: {out.get('encoder_used') or ''} | Coreg: {out.get('coreg_passed')}</p>
          <p>Chart: {json.dumps(out.get('chart_spec',{}))[:200]}</p>
          <p>Trace: {', '.join([t.get('agent','')+':'+t.get('status','') for t in (out.get('execution_trace') or [])[:6]] )}</p>
        </div>
        """
    html = f"""<html><head><meta charset="utf-8"><style>body{{font-family:Inter, sans-serif; padding:24px}} h1{{font-size:20px}} h3{{font-size:14px}}</style></head>
    <body><h1>Satiq Report — Session {session_id}</h1>
    <p>Methodology: LangGraph pipeline input_validator → router (Qwen) → planner → preprocessing → encoder_selector → encoder_compat → coreg_gate → vision_encoder → fusion → task_agent → tile_manager → post_processing → response_composer</p>
    {rows}
    <p style="font-size:10px;color:#666">Generated by Satiq orchestrator • audit trace included • CRS hard gate enforced</p>
    </body></html>"""
    return html

def generate_report(session_id: str, task_outputs: List[Dict[str, Any]], format: Literal["pdf","docx","html"] = "pdf") -> bytes:
    """Generate report bytes. Tries reportlab for PDF, python-docx for DOCX, fallback HTML."""
    if format == "docx":
        try:
            from docx import Document  # type: ignore
            doc = Document()
            doc.add_heading(f"Satiq Report — Session {session_id}", 1)
            doc.add_paragraph("Methodology: LangGraph pipeline with mocked Qwen 3.5 9B router/planner/composer, dummy vision encoders, confidence gates, retry loops.")
            for i, out in enumerate(task_outputs):
                doc.add_heading(f"{i+1}. {out.get('task','')} — {out.get('query','')[:80]}", level=2)
                doc.add_paragraph(f"Answer: {out.get('answer_text','')}")
                doc.add_paragraph(f"Confidence: {out.get('confidence')} | Trace: {', '.join([t.get('agent','') for t in (out.get('execution_trace') or [])])}")
                if out.get("chart_spec"):
                    doc.add_paragraph(f"Chart: {json.dumps(out['chart_spec'])[:300]}")
            buf = io.BytesIO()
            doc.save(buf)
            return buf.getvalue()
        except Exception as e:
            # fallback to html bytes labeled as docx
            return _html_for_pdf(session_id, task_outputs).encode()
    if format == "pdf":
        try:
            from reportlab.pdfgen import canvas  # type: ignore
            from reportlab.lib.pagesizes import A4  # type: ignore
            buf = io.BytesIO()
            c = canvas.Canvas(buf, pagesize=A4)
            w,h = A4
            y = h - 40
            c.setFont("Helvetica-Bold", 14)
            c.drawString(40, y, f"Satiq Report — Session {session_id}")
            y -= 20
            c.setFont("Helvetica", 8)
            c.drawString(40, y, "Methodology: LangGraph pipeline input_validator → ... → response_composer")
            y -= 24
            for i, out in enumerate(task_outputs):
                if y < 100:
                    c.showPage()
                    y = h - 40
                c.setFont("Helvetica-Bold", 10)
                c.drawString(40, y, f"{i+1}. {out.get('task','')} — {out.get('query','')[:60]}")
                y -= 14
                c.setFont("Helvetica", 8)
                txt = out.get('answer_text','')[:300]
                # simple wrap
                for line in [txt[j:j+100] for j in range(0, len(txt), 100)]:
                    c.drawString(40, y, line)
                    y -= 12
                    if y < 80:
                        c.showPage()
                        y = h - 40
                c.drawString(40, y, f"Confidence: {out.get('confidence')} | Categories: {out.get('change_categories') or out.get('class_map_rle')}")
                y -= 18
            c.save()
            return buf.getvalue()
        except Exception:
            # fallback: return HTML as pdf-like bytes (caller can treat as html)
            return _html_for_pdf(session_id, task_outputs).encode()
    # html
    return _html_for_pdf(session_id, task_outputs).encode()

def save_report(session_id: str, task_outputs: List[Dict[str, Any]], format: str = "pdf", out_dir: str = "orchestrator/storage/reports") -> str:
    data = generate_report(session_id, task_outputs, format=format)  # type: ignore
    p = Path(out_dir) / f"{session_id}.{format}"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)
    return str(p)
