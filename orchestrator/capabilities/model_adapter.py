"""Pluggable model adapter — no mocks, no hardcoded weights.

User will provide `models/{vqa,grounding,change,fusion}/inference.py` with fixed signatures.
Until those files exist, any request that needs a vision model returns a structured
permanent error MODEL_NOT_LINKED with a clear message. This keeps the pipeline
honest: greeting/chitchat/help skip models and still succeed, but real geospatial tasks
fail fast with an actionable error instead of inventing dummy bboxes/confidence.

Do NOT edit this file to add dummy fallbacks — wait for the 4 inference.py files.
"""
from __future__ import annotations
import importlib.util
import sys
from pathlib import Path
from typing import Any, Dict, Tuple

from orchestrator.core.config import get_settings

# Mapping task_type -> actual model1/2/3/4 layout (DO NOT EDIT the inference scripts themselves)
# model1 = VQA (GeoChat-7B run_inference.py), model2 = Grounding (GroundingDINO), model3 = Change-VQA (Prithvi+Vicuna), model4 = Fusion (CROMA)
MODEL_MAP: Dict[str, Dict[str, str]] = {
    "vqa": {"dir": "model1", "module": "models.model1.run_inference", "file": "models/model1/run_inference.py", "shim": "orchestrator.capabilities.shims.model1_shim"},
    "captioning": {"dir": "model1", "module": "models.model1.run_inference", "file": "models/model1/run_inference.py", "shim": "orchestrator.capabilities.shims.model1_shim"},
    "grounding": {"dir": "model2", "module": "models.model2.train", "file": "models/model2/visualize_pipeline_graph.py", "shim": "orchestrator.capabilities.shims.model2_shim"},
    "change_vqa": {"dir": "model3", "module": "models.model3.visualize_index_hybrid", "file": "models/model3/visualize_index_hybrid.py", "shim": "orchestrator.capabilities.shims.model3_shim"},
    "optical_sar_fusion": {"dir": "model4", "module": "models.model4.infer", "file": "models/model4/infer.py", "shim": "orchestrator.capabilities.shims.model4_shim"},
}

REPO_ROOT = Path(__file__).resolve().parents[2]


def _models_root() -> Path:
    s = get_settings()
    # allow override via MODELS_ROOT env, default "models"
    raw = getattr(s, "models_root", "models")
    p = Path(raw)
    if not p.is_absolute():
        p = REPO_ROOT / p
    return p


def is_model_linked(task_type: str) -> Tuple[bool, str]:
    """Check if model file exists for task_type via shim or original. Returns (linked, path)."""
    info = MODEL_MAP.get(task_type)
    if not info:
        return False, f"unknown task_type {task_type}"
    # Prefer shim (which wraps the original without editing it)
    shim_path = None
    shim_mod = info.get("shim")
    if shim_mod:
        shim_file = REPO_ROOT / (shim_mod.replace(".", "/") + ".py")
        if shim_file.exists():
            orig = REPO_ROOT / info["file"]
            if orig.exists():
                return True, str(orig)
            return False, f"original {info['file']} not found (shim present but source missing)"
    # Direct check: original file
    orig = REPO_ROOT / info["file"]
    if orig.exists():
        return True, str(orig)
    # Fallback: legacy inference.py naming
    root = _models_root()
    fp = root / info["dir"] / "inference.py"
    alt = REPO_ROOT / info["file"]
    if fp.exists() or alt.exists():
        return True, str(fp if fp.exists() else alt)
    return False, f"missing {info['file']} — expected at {orig} (do not rename original)"


def _load_inference_module(task_type: str):
    info = MODEL_MAP.get(task_type)
    if not info:
        raise ImportError(f"Unknown task_type {task_type}")
    # Prefer shim that wraps original without editing it
    shim_mod = info.get("shim")
    if shim_mod:
        shim_file = REPO_ROOT / (shim_mod.replace(".", "/") + ".py")
        if shim_file.exists():
            if str(REPO_ROOT) not in sys.path:
                sys.path.insert(0, str(REPO_ROOT))
            spec = importlib.util.spec_from_file_location(shim_mod, shim_file)
            if spec and spec.loader:
                mod = importlib.util.module_from_spec(spec)
                sys.modules[shim_mod] = mod
                spec.loader.exec_module(mod)  # type: ignore
                return mod
    root = _models_root()
    candidates = [root / info["dir"] / "inference.py", REPO_ROOT / info["file"]]
    fp = next((p for p in candidates if p.exists()), None)
    if fp is None:
        raise FileNotFoundError(f"MODEL_NOT_LINKED: {info['file']} not found. Place file at {REPO_ROOT / info['file']}")
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    spec = importlib.util.spec_from_file_location(info["module"], fp)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot load {fp}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[info["module"]] = mod
    spec.loader.exec_module(mod)  # type: ignore
    return mod


def call_model(task_type: str, query: str, image_paths: list[str], assets: list[Dict[str, Any]] | None = None) -> Dict[str, Any]:
    """Dispatch to the pluggable inference.py.

    Contract (strict, no mocks):
      - If inference.py missing → raise FileNotFoundError with MODEL_NOT_LINKED (permanent)
      - If inference.py exists but raises → wrap as MODEL_INFERENCE_ERROR (transient)
      - If inference.py returns dict → validate required keys {status, text|bbox, confidence, artifacts}
        and return normalized task_output shape.

    Expected inference.py signatures (do NOT change them):
      - vqa/inference.py:        def inference(image_path: str, query: str) -> dict
      - grounding/inference.py:  def inference(image_path: str, query: str) -> dict  # bbox_xyxy + text
      - change/inference.py:     def inference(image_t1: str, image_t2: str, query: str) -> dict
      - fusion/inference.py:     def inference(optical_path: str, sar_path: str, query: str) -> dict

    If your inference.py uses different names, this adapter probes common aliases.
    """
    linked, reason = is_model_linked(task_type)
    if not linked:
        raise FileNotFoundError(
            f"MODEL_NOT_LINKED: {task_type} requires {reason}. "
            f"Add models/{MODEL_MAP.get(task_type, {}).get('dir','?')}/inference.py (do not mock)."
        )
    mod = _load_inference_module(task_type)
    # Shim contract is def inference(*args) — probe it first, then original names
    handler = None
    for name in ("inference", "run", "predict", "infer", "call", "ask_geochat", "run_inference"):
        if hasattr(mod, name) and callable(getattr(mod, name)):
            handler = getattr(mod, name)
            break
    if handler is None:
        raise AttributeError(f"{MODEL_MAP[task_type]['file']} has no callable inference/run/predict (checked shim)")

    try:
        # Call with strict original inputs — no radiometric/resampling alteration before model
        if task_type in ("vqa", "captioning", "grounding"):
            # single image — pass exact path provided, no pre-resampling
            img = image_paths[0] if image_paths else ""
            result = handler(img, query) if handler.__code__.co_argcount >= 2 else handler(image_path=img, query=query)  # type: ignore
        elif task_type == "change_vqa":
            t1 = image_paths[0] if len(image_paths) >= 1 else ""
            t2 = image_paths[1] if len(image_paths) >= 2 else ""
            try:
                result = handler(t1, t2, query)
            except TypeError:
                result = handler(image_t1=t1, image_t2=t2, query=query)  # type: ignore
        elif task_type == "optical_sar_fusion":
            opt = image_paths[0] if len(image_paths) >= 1 else ""
            sar = image_paths[1] if len(image_paths) >= 2 else ""
            try:
                result = handler(opt, sar, query)
            except TypeError:
                result = handler(optical_path=opt, sar_path=sar, query=query)  # type: ignore
        else:
            result = handler(query, image_paths)  # fallback
    except FileNotFoundError:
        raise
    except Exception as e:
        # Wrap as transient inference error — retryable once
        raise RuntimeError(f"MODEL_INFERENCE_ERROR: {task_type} inference failed: {e}") from e

    # Normalize: shim already returns dict; if raw str returned, wrap
    if isinstance(result, str):
        result = {"text": result, "answer_text": result, "confidence": None}
    if not isinstance(result, dict):
        raise RuntimeError(f"MODEL_INFERENCE_ERROR: {task_type} inference returned non-dict")
    result["_inference_file"] = str(REPO_ROOT / MODEL_MAP[task_type]["file"])
    return result


def list_linked_models() -> Dict[str, bool]:
    return {k: is_model_linked(k)[0] for k in MODEL_MAP}
